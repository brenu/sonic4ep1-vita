#!/usr/bin/env bash
set -euo pipefail
PROJECT_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
export VITASDK="${VITASDK:-/usr/local/vitasdk}"
export PATH="$VITASDK/bin:$PATH"

python3 "$PROJECT_ROOT/tools/preflight.py"
cmake -S "$PROJECT_ROOT" -B "$PROJECT_ROOT/work/build" \
  -DCMAKE_BUILD_TYPE=Debug \
  -DSONIC_PERFORMANCE_PROFILE="${SONIC_PERFORMANCE_PROFILE:-ON}" \
  -DSONIC_VITAGL_PROFILING="${SONIC_VITAGL_PROFILING:-OFF}" \
  -DSONIC_IO_PROFILE="${SONIC_IO_PROFILE:-OFF}" \
  -DSONIC_AUDIO_PROFILE="${SONIC_AUDIO_PROFILE:-OFF}" \
  -DSONIC_VITAGL_WVP_ON_GPU="${SONIC_VITAGL_WVP_ON_GPU:-ON}" \
  -DSONIC_VITAGL_NO_TILE_CLIPPER="${SONIC_VITAGL_NO_TILE_CLIPPER:-OFF}" \
  -DSONIC_VITAGL_SKIP_ERROR_HANDLING="${SONIC_VITAGL_SKIP_ERROR_HANDLING:-OFF}" \
  -DSONIC_VITAGL_SAFE_DRAW_SPEEDHACK="${SONIC_VITAGL_SAFE_DRAW_SPEEDHACK:-OFF}" \
  -DSONIC_VITAGL_NO_DMAC="${SONIC_VITAGL_NO_DMAC:-OFF}" \
  -DSONIC_HOST_OPT_LEVEL="${SONIC_HOST_OPT_LEVEL:-3}"
cmake --build "$PROJECT_ROOT/work/build" -j2

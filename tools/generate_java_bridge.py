#!/usr/bin/env python3
"""Generate JNI descriptors and FalsoJNI dispatch arrays from verified analysis."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
entries = json.loads((ROOT / 'work/analysis/java_callbacks.json').read_text())['initNative']['lookups']
assert len(entries) == 82 and all(e['smali_declaration_found'] and e['class_name'] for e in entries)
assert len({(e['class_name'], e['name'], e['signature']) for e in entries}) == len(entries)
extensions = json.loads((ROOT / 'tools/extension_callbacks.json').read_text())
for e in extensions:
    smali = (ROOT / 'work/apkdecoded/smali' / (e['class_name'] + '.smali')).read_text()
    declaration = e['name'] + e['signature']
    assert any(line.startswith('.method ') and line.split()[-1] == declaration
               for line in smali.splitlines()), declaration
methods = [e for e in entries if e['kind'] == 'method'] + extensions
fields = [e for e in entries if e['kind'] == 'field']
ordinary = [e for e in methods if e['name'] != '<init>']
assert len({e['name'] for e in ordinary}) == len(ordinary), 'FalsoJNI name dispatch would collide'
assert len({(e['class_name'], e['name'], e['signature']) for e in methods}) == len(methods)
q = json.dumps
types = {'V': 'Void', 'L': 'Object', '[': 'Object', 'Z': 'Boolean', 'I': 'Int', 'J': 'Long',
         'F': 'Float', 'D': 'Double', 'B': 'Byte', 'C': 'Char', 'S': 'Short'}
for i, e in enumerate(methods, 1):
    e['id'] = i if i <= 80 else 2001 + i - 81
    e['type'] = types[e['signature'].split(')')[1][0]]
for i, e in enumerate(fields, 1001):
    e['id'] = i
lines = ['/* Generated by tools/generate_java_bridge.py; do not edit by hand. */',
         'const SonicJavaDescriptor sonic_java_descriptors[] = {']
for e in methods + fields:
    lines.append('    {%d, %s, %s, %s, %d},' % (e['id'], q(e['class_name']), q(e['name']),
                                              q(e['signature']), e['kind'] == 'field'))
lines += ['};', 'const size_t sonic_java_descriptor_count = sizeof(sonic_java_descriptors) / sizeof(sonic_java_descriptors[0]);']
(ROOT / 'source/sonic_java_descriptors.inc').write_text('\n'.join(lines) + '\n')
lines = ['/* Generated by tools/generate_java_bridge.py; do not edit by hand. */', 'NameToMethodID nameToMethodId[] = {']
for e in methods:
    # Constructors use class/signature-aware NewObject hooks, not the upstream
    # name-only lookup table, which cannot distinguish multiple <init> names.
    if e['name'] != '<init>':
        lines.append('    {%d, %s, METHOD_TYPE_%s},' % (e['id'], q(e['name']), e['type'].upper()))
lines += ['};']
for t in sorted(set(types.values())):
    lines.append(f'Methods{t} methods{t}[] = {{')
    for e in methods:
        if e['type'] == t:
            lines.append('    {%d, sonic_java_%s},' % (e['id'], t.lower()))
    lines.append('};')
lines += ['NameToFieldID nameToFieldId[] = {']
for e in fields:
    lines.append('    {%d, %s, FIELD_TYPE_OBJECT},' % (e['id'], q(e['name'])))
lines += ['};', 'FieldsObject fieldsObject[] = {']
objects = {'m_MediaPlayerManager': 'SONIC_OBJECT_MEDIA', 'm_LoaderKeyboard': 'SONIC_OBJECT_KEYBOARD'}
for e in fields:
    lines.append('    {%d, %s},' % (e['id'], objects[e['name']] ))
lines += ['};']
for t in sorted(set(types.values()) - {'Object', 'Void'}):
    lines.append(f'Fields{t} fields{t}[] = {{}};')
lines += ['__FALSOJNI_IMPL_CONTAINER_SIZES']
(ROOT / 'source/sonic_java_dispatch.inc').write_text('\n'.join(lines) + '\n')
print('Generated', len(methods), 'methods and', len(fields), 'fields')
